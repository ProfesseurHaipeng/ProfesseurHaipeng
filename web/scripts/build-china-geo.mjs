// Precompile simplified province outlines into src/lib/chinaGeo.ts so the
// site can render inline mini China maps (all 34 province-level units incl.
// Taiwan, Hong Kong, Macao, plus the South China Sea dash line) and highlight
// one region. Data: DataV.GeoAtlas (AutoNavi) 100000_full.json.
// Usage: node scripts/build-china-geo.mjs [path/to/100000_full.json]
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const source = process.argv[2] || "/tmp/china_full.json"
const out = resolve(process.cwd(), "src/lib/chinaGeo.ts")
const geo = JSON.parse(readFileSync(source, "utf8"))

const LON = [73.2, 135.4]
const LAT = [2.6, 53.9]
const W = 380
const K = W / ((LON[1] - LON[0]) * Math.cos((32 * Math.PI) / 180))
const H = Math.round((LAT[1] - LAT[0]) * K)

const px = (lon, lat) => [
  Number(((lon - LON[0]) * K * Math.cos((32 * Math.PI) / 180)).toFixed(1)),
  Number(((LAT[1] - lat) * K).toFixed(1)),
]

const KEEP_SMALL = new Set(["香港特别行政区", "澳门特别行政区"])

function ringPath(ring, aggressive) {
  const step = aggressive && ring.length > 100 ? 3 : ring.length > 40 ? 2 : 1
  const pts = ring.filter((_, i) => i % step === 0)
  let d = ""
  let last = ""
  for (const [lon, lat] of pts) {
    const [x, y] = px(lon, lat)
    const key = `${x} ${y}`
    if (key === last) continue
    d += (d ? "L" : "M") + key
    last = key
  }
  return d ? `${d}Z` : ""
}

function ringBboxPx(ring) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
  for (const [lon, lat] of ring) {
    const [x, y] = px(lon, lat)
    if (x < minX) minX = x
    if (y < minY) minY = y
    if (x > maxX) maxX = x
    if (y > maxY) maxY = y
  }
  return Math.max(maxX - minX, maxY - minY)
}

function shortName(name) {
  return name
    .replace(/(维吾尔|壮族|回族)?自治区$/, "")
    .replace(/特别行政区$/, "")
    .replace(/[省市]$/, "")
}

const provinces = []
let dash = ""

for (const feature of geo.features) {
  const { name, adcode, centroid, center } = feature.properties
  const polys = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates
  const keepSmall = KEEP_SMALL.has(name)
  const paths = []
  for (const poly of polys) {
    for (const ring of poly) {
      if (!keepSmall && ring.length < 12 && ringBboxPx(ring) < 2) continue
      const d = ringPath(ring, !keepSmall)
      if (d) paths.push(d)
    }
  }
  const d = paths.join("")
  if (!d) continue
  if (String(adcode) === "100000_JD") {
    dash = d
    continue
  }
  const anchor = centroid || center
  const [cx, cy] = anchor ? px(anchor[0], anchor[1]) : [0, 0]
  provinces.push({ name, short: shortName(name), d, cx, cy })
}

const ts = `// Generated by scripts/build-china-geo.mjs — do not edit by hand.
// Simplified province outlines (incl. Taiwan, Hong Kong, Macao, and the
// South China Sea dash line). Data: DataV.GeoAtlas / AutoNavi.

export type ProvinceShape = {
  name: string
  short: string
  d: string
  cx: number
  cy: number
}

export const CHINA_VIEWBOX = "0 0 ${W} ${H}"

export const CHINA_DASH_LINE = ${JSON.stringify(dash)}

export const CHINA_PROVINCES: ProvinceShape[] = ${JSON.stringify(provinces)}

/** Find the province a region name belongs to, e.g. 湖南南部 → 湖南省. */
export function matchProvince(regionName: string): ProvinceShape | null {
  const key = regionName.trim()
  if (!key) return null
  for (const province of CHINA_PROVINCES) {
    if (key === province.name || key === province.short) return province
    if (key.startsWith(province.short)) return province
  }
  return null
}
`

writeFileSync(out, ts)
console.log("wrote", out, Math.round(ts.length / 1024), "KB,", provinces.length, "provinces,", `${W}x${H}`)
